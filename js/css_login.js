function reg() {
  	document.getElementById("login").style.display = "none";
  	document.getElementById("reg").style.display = "block";
  	document.getElementById("login-t").style.display = "none";
  	document.getElementById("reg-t").style.display = "block";
}

function log() {
	document.getElementById("login").style.display = "block";
	document.getElementById("reg").style.display = "none";
	document.getElementById("login-t").style.display = "block";
	document.getElementById("reg-t").style.display = "none";
}
